import { useCallback, useEffect, useRef, useState } from "react";
import type { ProjectListItem, Sample, ScanEvent } from "@api/types";
import { api, cleanMessage, formatWhen, isoTime, toApiError, VERDICT_LABEL, type ScanRequest } from "../api";
import { href, navigate } from "../App";
import { Empty, ErrorState, Loading } from "./States";

const SUPPORTED: { group: string; files: string[] }[] = [
  { group: "JavaScript lockfiles", files: ["package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lock"] },
  { group: "Python lockfiles", files: ["uv.lock", "poetry.lock", "requirements.txt"] },
  { group: "AI tool MCP configs", files: [".mcp.json", "claude_desktop_config.json", ".cursor/mcp.json", ".vscode/mcp.json"] },
];

/** Guess a filename for pasted contents so the server picks the right parser. */
export function guessFilename(content: string): string | null {
  const t = content.trim();
  if (!t) return null;
  if (t.startsWith("{")) {
    if (/"mcpServers"\s*:/.test(t)) return ".mcp.json";
    if (/"lockfileVersion"/.test(t) && /"packages"\s*:/.test(t)) return "package-lock.json";
    if (/"workspaces"\s*:/.test(t)) return "bun.lock";
    if (/"servers"\s*:/.test(t)) return ".vscode/mcp.json";
    if (/"lockfileVersion"/.test(t)) return "package-lock.json";
  }
  if (/^# yarn lockfile v1/m.test(t) || /^__metadata:/m.test(t)) return "yarn.lock";
  if (/^lockfileVersion:/m.test(t)) return "pnpm-lock.yaml";
  if (/@generated by Poetry/i.test(t)) return "poetry.lock";
  if (/^\[\[package\]\]/m.test(t) && /registry\s*=\s*"https:\/\/pypi\.org/.test(t)) return "uv.lock";
  if (/^\[\[package\]\]/m.test(t)) return "uv.lock";
  if (/^\s*[A-Za-z0-9][A-Za-z0-9._-]*(\[[^\]]*\])?\s*==\s*[0-9][^\s;#]*/m.test(t)) return "requirements.txt";
  return null;
}

type StageRow = { stage: string; message: string; state: "done" | "active" | "failed" };
type ScanState =
  | { status: "idle" }
  | { status: "running" | "error" | "done"; label: string; stages: StageRow[]; pct: number; message: string; error?: string };

function describe(req: ScanRequest, samples: Sample[] | null): string {
  if ("sample" in req) return samples?.find((s) => s.id === req.sample)?.title ?? req.sample;
  if ("githubUrl" in req) return req.githubUrl.replace(/^https?:\/\/(www\.)?/, "");
  return req.filename;
}

export default function Intake() {
  const [samples, setSamples] = useState<Sample[] | null>(null);
  const [samplesError, setSamplesError] = useState<unknown>(null);
  const [projects, setProjects] = useState<ProjectListItem[] | null>(null);
  const [projectsError, setProjectsError] = useState<unknown>(null);
  const [scan, setScan] = useState<ScanState>({ status: "idle" });
  const [dragging, setDragging] = useState(false);
  const [pasteOpen, setPasteOpen] = useState(false);
  const [paste, setPaste] = useState("");
  const [pasteName, setPasteName] = useState("");
  const [github, setGithub] = useState("");
  const [inputError, setInputError] = useState<string | null>(null);
  const lastReq = useRef<ScanRequest | null>(null);
  const panelRef = useRef<HTMLDivElement>(null);
  const abortRef = useRef<AbortController | null>(null);

  useEffect(() => {
    document.title = "Scan · Taintgraph";
  }, []);

  const loadSamples = useCallback(() => {
    setSamplesError(null);
    api.samples().then(setSamples, (e) => setSamplesError(e));
  }, []);
  const loadProjects = useCallback(() => {
    setProjectsError(null);
    api.projects().then(setProjects, (e) => setProjectsError(e));
  }, []);
  useEffect(() => {
    loadSamples();
    loadProjects();
    return () => abortRef.current?.abort();
  }, [loadSamples, loadProjects]);

  const guessed = guessFilename(paste);
  const pasteFilename = pasteName.trim() || guessed || "";

  const run = useCallback(
    async (req: ScanRequest) => {
      lastReq.current = req;
      abortRef.current?.abort();
      const ctrl = new AbortController();
      abortRef.current = ctrl;
      setInputError(null);
      setScan({ status: "running", label: describe(req, samples), stages: [], pct: 0, message: "Starting the scan" });
      requestAnimationFrame(() => {
        const el = panelRef.current;
        if (el) {
          el.scrollIntoView({ block: "center", behavior: window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth" });
          el.focus({ preventScroll: true });
        }
      });
      let finished = false;
      const onEvent = (ev: ScanEvent) => {
        if (ev.type === "progress") {
          setScan((s) => {
            if (s.status === "idle") return s;
            const stages = s.stages.map((r) => (r.state === "active" ? { ...r, state: "done" as const } : r));
            const existing = stages.findIndex((r) => r.stage === ev.stage);
            if (existing >= 0) stages[existing] = { stage: ev.stage, message: ev.message, state: "active" };
            else stages.push({ stage: ev.stage, message: ev.message, state: "active" });
            return { ...s, stages, pct: Math.max(0, Math.min(100, ev.pct)), message: ev.message };
          });
        } else if (ev.type === "done") {
          finished = true;
          setScan((s) => (s.status === "idle" ? s : { ...s, status: "done", pct: 100, message: "Scan finished. Opening the project.", stages: s.stages.map((r) => ({ ...r, state: "done" })) }));
          navigate(href.project(ev.projectId));
        } else if (ev.type === "error") {
          finished = true;
          fail(cleanMessage(ev.message));
        }
      };
      const fail = (message: string) =>
        setScan((s) => {
          if (s.status === "idle") return s;
          const stages = [...s.stages];
          const idx = stages.map((r) => r.state).lastIndexOf("active");
          if (idx >= 0) stages[idx] = { ...stages[idx], state: "failed" };
          else if (stages.length) stages[stages.length - 1] = { ...stages[stages.length - 1], state: "failed" };
          return { ...s, status: "error", stages, error: message };
        });
      try {
        await api.scan(req, onEvent, ctrl.signal);
        if (!finished && !ctrl.signal.aborted) fail("The server closed the connection before the scan finished.");
      } catch (e) {
        if (ctrl.signal.aborted) return;
        fail(toApiError(e).message);
      }
    },
    [samples],
  );

  const readFile = async (file: File) => {
    if (file.size > 25 * 1024 * 1024) {
      setInputError("That file is larger than 25 MB. Taintgraph reads lockfiles and MCP configs, which are usually much smaller.");
      return;
    }
    try {
      const content = await file.text();
      run({ filename: file.name, content });
    } catch {
      setInputError("Taintgraph couldn't read that file. Try choosing it again or paste its contents instead.");
    }
  };

  const onDrop = (e: React.DragEvent) => {
    e.preventDefault();
    setDragging(false);
    const file = e.dataTransfer.files?.[0];
    if (file) void readFile(file);
  };

  const onGithub = (e: React.FormEvent) => {
    e.preventDefault();
    const url = github.trim();
    if (!/^https?:\/\/(www\.)?github\.com\/[^/\s]+\/[^/\s]+/i.test(url) && !/^[\w.-]+\/[\w.-]+$/.test(url)) {
      setInputError("Enter a GitHub repository URL, like https://github.com/owner/repo.");
      return;
    }
    run({ githubUrl: /^https?:/i.test(url) ? url : `https://github.com/${url}` });
  };

  const onPaste = (e: React.FormEvent) => {
    e.preventDefault();
    if (!paste.trim()) {
      setInputError("Paste the contents of a lockfile or MCP config first.");
      return;
    }
    if (!pasteFilename) {
      setInputError("Taintgraph couldn't tell what kind of file this is. Type its filename, like package-lock.json.");
      return;
    }
    run({ filename: pasteFilename, content: paste });
  };

  const busy = scan.status === "running";

  return (
    <div className="page intake">
      <section className="intake-hero" aria-labelledby="page-title">
        <h1 id="page-title" tabIndex={-1}>
          Find out how a compromise reaches your app.
        </h1>
        <p className="lede">
          Give Taintgraph a lockfile or an AI tool's MCP config. It maps every package, who can publish it, and which
          advisories touch it, then traces the exact route anything dangerous takes into your code.
        </p>
      </section>

      <div className="intake-grid">
        <section className="intake-inputs" aria-label="Choose what to scan">
          <div
            className={dragging ? "dropzone dragging" : "dropzone"}
            onDragOver={(e) => {
              e.preventDefault();
              setDragging(true);
            }}
            onDragLeave={() => setDragging(false)}
            onDrop={onDrop}
          >
            <p className="dropzone-title">Drop a file here</p>
            <p className="muted">or</p>
            <input
              id="file-input"
              className="file-input"
              type="file"
              accept=".json,.yaml,.yml,.lock,.txt,.toml"
              aria-label="Choose a lockfile or MCP config to scan"
              disabled={busy}
              onChange={(e) => {
                const f = e.target.files?.[0];
                if (f) void readFile(f);
                e.target.value = "";
              }}
            />
            <label htmlFor="file-input" className="btn btn-primary file-label" aria-hidden="true">
              Choose a file
            </label>
            <div className="supported">
              {SUPPORTED.map((g) => (
                <div key={g.group}>
                  <p className="supported-group">{g.group}</p>
                  <ul>
                    {g.files.map((f) => (
                      <li key={f}>
                        <code>{f}</code>
                      </li>
                    ))}
                  </ul>
                </div>
              ))}
            </div>
          </div>

          <details className="paste" open={pasteOpen} onToggle={(e) => setPasteOpen((e.target as HTMLDetailsElement).open)}>
            <summary>Paste contents instead</summary>
            <form onSubmit={onPaste} className="paste-form">
              <label htmlFor="paste-text">File contents</label>
              <textarea
                id="paste-text"
                rows={8}
                spellCheck={false}
                value={paste}
                onChange={(e) => setPaste(e.target.value)}
                placeholder={'{\n  "lockfileVersion": 3,\n  "packages": { … }\n}'}
              />
              <div className="paste-row">
                <div className="field">
                  <label htmlFor="paste-name">Filename</label>
                  <input
                    id="paste-name"
                    type="text"
                    value={pasteName}
                    placeholder={guessed ?? "package-lock.json"}
                    onChange={(e) => setPasteName(e.target.value)}
                    aria-describedby="paste-guess"
                  />
                  <p id="paste-guess" className="hint">
                    {guessed && !pasteName ? (
                      <>
                        Looks like <code>{guessed}</code>.
                      </>
                    ) : paste.trim() && !guessed ? (
                      "Couldn't tell the file type. Type its filename."
                    ) : (
                      "Taintgraph guesses this from the contents."
                    )}
                  </p>
                </div>
                <button type="submit" className="btn btn-primary" disabled={busy}>
                  Scan pasted contents
                </button>
              </div>
            </form>
          </details>

          <form className="github-form" onSubmit={onGithub}>
            <label htmlFor="github-url">GitHub repository</label>
            <p className="hint" id="github-hint">
              Taintgraph fetches the lockfiles and MCP configs from a public repository.
            </p>
            <div className="inline-field">
              <input
                id="github-url"
                type="url"
                inputMode="url"
                autoComplete="off"
                placeholder="https://github.com/owner/repo"
                value={github}
                onChange={(e) => setGithub(e.target.value)}
                aria-describedby="github-hint"
              />
              <button type="submit" className="btn btn-primary" disabled={busy}>
                Scan
              </button>
            </div>
          </form>

          {inputError && (
            <p className="input-error" role="alert">
              {inputError}
            </p>
          )}
        </section>

        <section className="samples" aria-labelledby="samples-h">
          <h2 id="samples-h">Or try a sample</h2>
          <p className="muted">Real incidents, rebuilt as lockfiles. One click scans it.</p>
          {samplesError ? (
            <ErrorState error={samplesError} onRetry={loadSamples} />
          ) : !samples ? (
            <Loading label="Loading samples" compact />
          ) : samples.length === 0 ? (
            <Empty title="No samples on this server." />
          ) : (
            <ul className="sample-list">
              {samples.map((s) => (
                <li key={s.id}>
                  <button type="button" className="sample" onClick={() => run({ sample: s.id })} disabled={busy}>
                    <span className="sample-title">{s.title}</span>
                    <span className="sample-desc">{s.description}</span>
                    <code className="sample-file">{s.filename}</code>
                  </button>
                </li>
              ))}
            </ul>
          )}
        </section>
      </div>

      {scan.status !== "idle" && (
        <section
          ref={panelRef}
          tabIndex={-1}
          className={`scan-panel scan-${scan.status}`}
          aria-labelledby="scan-h"
        >
          <h2 id="scan-h">
            {scan.status === "error" ? "Scan stopped" : scan.status === "done" ? "Scan finished" : "Scanning"}{" "}
            <span className="scan-target">{scan.label}</span>
          </h2>
          <div
            className="bar"
            role="progressbar"
            aria-label="Scan progress"
            aria-valuemin={0}
            aria-valuemax={100}
            aria-valuenow={Math.round(scan.pct)}
          >
            <span style={{ width: `${scan.pct}%` }} />
          </div>
          <p className="scan-message" role="status" aria-live="polite">
            {scan.status === "error" ? `Scan stopped: ${scan.error}` : scan.message}
          </p>
          {scan.stages.length > 0 && (
            <ol className="stages">
              {scan.stages.map((r) => (
                <li key={r.stage} className={`stage stage-${r.state}`}>
                  <span className="stage-mark" aria-hidden="true" />
                  <span className="stage-name">{r.stage}</span>
                  <span className="visually-hidden">
                    {r.state === "done" ? " (done)" : r.state === "failed" ? " (failed)" : " (in progress)"}
                  </span>
                  <span className="stage-msg">{r.message}</span>
                </li>
              ))}
            </ol>
          )}
          {scan.status === "error" && (
            <button type="button" className="btn btn-primary" onClick={() => lastReq.current && run(lastReq.current)}>
              Try again
            </button>
          )}
        </section>
      )}

      <section className="projects" aria-labelledby="projects-h">
        <h2 id="projects-h">Your projects</h2>
        {projectsError ? (
          <ErrorState error={projectsError} onRetry={loadProjects} />
        ) : !projects ? (
          <Loading label="Loading your projects" compact />
        ) : projects.length === 0 ? (
          <Empty title="No projects yet — scan a lockfile or try a sample" />
        ) : (
          <ul className="project-list">
            {[...projects]
              .sort((a, b) => b.scannedAt - a.scannedAt)
              .map((p) => (
                <li key={p.id}>
                  <a href={href.project(p.id)} className="project-row">
                    <span className="project-name">{p.name}</span>
                    <span className="project-meta">
                      {p.source} · <time dateTime={isoTime(p.scannedAt)}>{formatWhen(p.scannedAt)}</time>
                    </span>
                    <span className={`pill pill-${p.verdict}`}>{VERDICT_LABEL[p.verdict] ?? p.verdict}</span>
                  </a>
                </li>
              ))}
          </ul>
        )}
      </section>
    </div>
  );
}
