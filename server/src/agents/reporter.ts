import { read, run } from "../db.ts";
import { Q } from "../queries.ts";
import { short, summary, untrusted } from "../analysis.ts";
import { COMPROMISE, type FindingView } from "../types.ts";
import { fixPlan } from "../fix.ts";

// The Reporter turns the graph (and the Analyst's last conclusion) into an incident report a human can forward.

const md = (s: string) => untrusted(s).replace(/([\\`*_[\]<>|])/g, "\\$1");
const route = (f: FindingView, name: string) => f.path.map((k) => (k.startsWith("project/") ? name : short(k))).map(md).join(" → ");

export async function buildReport(org: string, projectId: string): Promise<string> {
  const s = await summary(org, projectId);
  const [inv] = await read(org, Q("investigation_recent"), { projectId });
  const live = s.findings.filter((f) => f.status === "open" || f.status === "confirmed");
  const bad = live.filter((f) => COMPROMISE.includes(f.signal));
  const other = live.filter((f) => !COMPROMISE.includes(f.signal));
  const reviewed = s.findings.filter((f) => f.status !== "open" && f.status !== "confirmed");
  const out: string[] = [];
  out.push(`# Supply-chain report: ${md(s.name)}`);
  out.push(`**Verdict: ${s.verdict.toUpperCase()}** · ${s.source} · scanned ${new Date(s.scannedAt).toISOString().slice(0, 16).replace("T", " ")} UTC`);
  out.push(`${s.counts.packages} installed versions, ${s.counts.edges} dependency edges, ${s.counts.accounts} maintainer accounts, ${s.counts.advisories} matching advisories.`);
  if (bad.length) {
    out.push(`## Compromised versions (${bad.length})`);
    out.push(`Treat any machine that installed these as compromised: remove the version, rotate the tokens and keys it could read, and check CI logs from the install date.`);
    for (const f of bad) out.push(`- **${md(f.name)}@${md(f.version)}**: ${md(f.title)}\n  - Route: ${route(f, s.name)}${f.advisories.length ? `\n  - Advisories: ${f.advisories.map((a) => `[${md(a.id)}](${a.url})`).join(", ")}` : ""}${f.fix ? `\n  - Fix: ${md(f.fix)}` : ""}`);
  }
  if (other.length) {
    out.push(`## Other findings (${other.length})`);
    out.push(`| Severity | Signal | Package | Fix |\n|---|---|---|---|`);
    for (const f of other.slice(0, 40)) out.push(`| ${f.severity} | ${f.signal.replace(/_/g, " ")} | ${md(f.name)}@${md(f.version)} | ${md(f.fix ?? "")} |`);
    if (other.length > 40) out.push(`…and ${other.length - 40} more.`);
  }
  if (!live.length) out.push(`## No open findings\nNothing this project installs is named in a malware advisory, and no release looks tampered with.`);
  if (s.mcpServers.length) {
    out.push(`## MCP servers`);
    for (const m of s.mcpServers) out.push(`- ${md(m.name)} (${md(m.client)}): ${m.pinned ? "pinned" : "**unpinned**, runs whatever is latest at launch"}${m.packageKey ? `, runs ${md(short(m.packageKey))}` : ""}${m.advisories.length ? `, advisories: ${m.advisories.map(md).join(", ")}` : ""}`);
  }
  if (s.topAccounts.length) {
    out.push(`## Accounts with the most reach`);
    out.push(`One hijacked login can publish a new version of every package it maintains.`);
    for (const a of s.topAccounts.slice(0, 5)) out.push(`- ${md(a.login)}: ${a.versions} versions (${(a.share * 100).toFixed(0)}% of the tree)${a.flagged ? ", **touches a flagged version**" : ""}`);
  }
  const plan = await fixPlan(org, projectId).catch(() => null);
  if (plan?.items.length) {
    out.push(`## Fix plan`);
    out.push(`| Package | Move to | How | Note |\n|---|---|---|---|`);
    for (const i of plan.items.slice(0, 40))
      out.push(`| ${md(i.name)}@${md(i.from)} | ${i.to ? md(i.to) + (i.majorChange ? " (major)" : "") : i.action === "no_fix" ? "no fix yet" : "remove"} | ${i.direct ? "direct dependency" : "override"} | ${md(i.note)} |`);
    if (plan.npm) out.push(`Add to package.json (npm; pnpm uses \`pnpm.overrides\`, yarn uses \`resolutions\`):\n\n\`\`\`json\n${JSON.stringify({ overrides: plan.npm.overrides }, null, 2)}\n\`\`\``);
    if (plan.python) out.push(`Python:\n\n\`\`\`bash\n${plan.python.commands.join("\n")}\n\`\`\``);
    if (plan.incident.length) out.push(`### Incident response\n${plan.incident.map((s) => `- ${md(s)}`).join("\n")}`);
  }
  if (inv?.answer) out.push(`## Analyst's conclusion\n> ${md(inv.question)}\n\n${md(inv.answer).replace(/\n/g, "\n\n")}`);
  if (reviewed.length) out.push(`## Reviewed by people or memory (${reviewed.length})\n${reviewed.slice(0, 15).map((f) => `- ${md(f.name)}@${md(f.version)} ${f.signal.replace(/_/g, " ")}: ${f.status}${f.statusNote ? ` (${md(f.statusNote)})` : ""}`).join("\n")}`);
  out.push(`---\nGenerated by Taintgraph from a FalkorDB graph of this project's dependencies, maintainers, releases and OSV.dev advisories.`);
  const markdown = out.join("\n\n");
  await run(org, Q("report_set"), { projectId, markdown });
  return markdown;
}

export async function getReport(org: string, projectId: string): Promise<string> {
  const [row] = await read(org, Q("report_get"), { projectId });
  return row?.markdown ?? buildReport(org, projectId);
}
