import { parse as parseYaml, parseAllDocuments } from "yaml";
import { parse as parseToml } from "smol-toml";
import type { Ecosystem } from "../types.ts";

// Lockfiles and MCP configs -> a package graph: versions, dependency edges, and the project's direct dependencies.

export interface Pkg {
  key: string; // "npm/<name>@<version>" or "pypi/<normalized-name>@<version>"
  name: string;
  version: string;
  ecosystem: Ecosystem;
  dev: boolean;
  lockInstallScript?: boolean;
}

export interface McpRef {
  key: string;
  name: string;
  client: string;
  command: string;
  ecosystem: Ecosystem | null; // null: remote server or a local binary
  packageName: string | null;
  version: string | null; // null when not pinned
  pinned: boolean;
  resolvedKey?: string;
}

export interface Parsed {
  kind: "app" | "agent-config";
  name: string;
  source: string;
  packages: Map<string, Pkg>;
  edges: { from: string; to: string }[];
  direct: { key: string; dev: boolean }[];
  mcp: McpRef[];
}

export const normPy = (n: string) => n.toLowerCase().replace(/[-_.]+/g, "-");
export const npmKey = (name: string, v: string) => `npm/${name}@${v}`;
export const pypiKey = (name: string, v: string) => `pypi/${normPy(name)}@${v}`;
export const npmPackageKey = (name: string) => `npm/${name}`;
export const pypiPackageKey = (name: string) => `pypi/${normPy(name)}`;

/** Split "name@version" at the first "@" after a scope; "foo@git+https://git@host" keeps the whole URL as the version. */
export function splitSpec(spec: string): { name: string; version: string | null } {
  const at = spec.indexOf("@", 1);
  return at > 0 ? { name: spec.slice(0, at), version: spec.slice(at + 1) || null } : { name: spec, version: null };
}

/** Registry releases start with a digit; git, tarball, file, link and workspace specs are not registry packages. */
export const isRegistryVersion = (v: string | null | undefined): v is string => !!v && /^\d/.test(v) && !v.includes("://") && !v.includes("/");

const UNREADABLE = (f: string) =>
  `Couldn't read ${f}. Upload a package-lock.json, pnpm-lock.yaml, yarn.lock, bun.lock, uv.lock, poetry.lock, requirements.txt, or an MCP config (.mcp.json, claude_desktop_config.json, .cursor/mcp.json, .vscode/mcp.json).`;

export function parseInput(filename: string, content: string): Parsed {
  const f = filename.toLowerCase();
  const head = content.trimStart().slice(0, 4000);
  if (f.endsWith("bun.lockb")) throw new Error("bun.lockb is binary. Run `bun install --save-text-lockfile` and upload bun.lock.");
  if (f.endsWith("uv.lock") || (/^\[\[package\]\]/m.test(head) && /registry = "https:\/\/(pypi|files\.pythonhosted)/.test(head))) return uvLock(content, filename);
  if (f.endsWith("poetry.lock") || /@generated by Poetry/.test(head.slice(0, 300))) return poetryLock(content, filename);
  if (f.endsWith(".txt")) {
    const r = requirements(content, filename);
    if (r.packages.size) return r;
    throw new Error(`No pinned packages (name==version) in ${filename}. Upload a lockfile, a pinned requirements.txt, or an MCP config.`);
  }
  if (f.endsWith("bun.lock")) return bunLock(content, filename);
  if (f.endsWith("yarn.lock") || /^# (yarn lockfile v1|THIS IS AN AUTOGENERATED FILE)/m.test(head.slice(0, 300)) || /^__metadata:/m.test(head)) {
    return /^__metadata:/m.test(content) ? yarnBerry(content, filename) : yarnV1(content, filename);
  }
  if (f.endsWith(".yaml") || f.endsWith(".yml") || /^lockfileVersion:/m.test(head)) return pnpmLock(content, filename);
  let json: any;
  try {
    json = JSON.parse(content);
  } catch {
    throw new Error(UNREADABLE(filename));
  }
  if (json.lockfileVersion === 1) throw new Error("package-lock.json v1 isn't supported. Run `npm install --lockfile-version 3` and upload again.");
  if (json.lockfileVersion && json.packages) return packageLock(json, filename);
  if (json.mcpServers || json.servers || json.projects) return mcpConfig(json, filename);
  throw new Error(UNREADABLE(filename));
}

// ───────────── shared builder ─────────────
class Builder {
  packages = new Map<string, Pkg>();
  edges: { from: string; to: string }[] = [];
  private edgeSet = new Set<string>();
  direct = new Map<string, boolean>(); // key -> dev
  constructor(private eco: Ecosystem) {}
  add(name: string, version: string, extra: Partial<Pkg> = {}): Pkg | null {
    if (!isRegistryVersion(version)) return null;
    const key = this.eco === "npm" ? npmKey(name, version) : pypiKey(name, version);
    let p = this.packages.get(key);
    if (!p) {
      p = { key, name: this.eco === "npm" ? name : normPy(name), version, ecosystem: this.eco, dev: true, ...extra };
      this.packages.set(key, p);
    } else if (extra.lockInstallScript) p.lockInstallScript = true;
    return p;
  }
  edge(from: Pkg | null | undefined, to: Pkg | null | undefined) {
    if (!from || !to || from.key === to.key) return;
    const id = `${from.key}>${to.key}`;
    if (this.edgeSet.has(id)) return;
    this.edgeSet.add(id);
    this.edges.push({ from: from.key, to: to.key });
  }
  root(p: Pkg | null | undefined, dev: boolean) {
    if (!p) return;
    const cur = this.direct.get(p.key);
    this.direct.set(p.key, cur === undefined ? dev : cur && dev); // prod wins over dev
  }
  /** No roots declared (yarn v1, poetry): anything nothing depends on is a direct dependency. */
  inferRoots() {
    const targets = new Set(this.edges.map((e) => e.to));
    for (const p of this.packages.values()) if (!targets.has(p.key)) this.direct.set(p.key, false);
  }
  build(kind: Parsed["kind"], name: string, source: string): Parsed {
    // Everything reachable from a prod root is prod.
    const adj = new Map<string, string[]>();
    for (const e of this.edges) adj.set(e.from, [...(adj.get(e.from) ?? []), e.to]);
    const stack = [...this.direct].filter(([, dev]) => !dev).map(([k]) => k);
    while (stack.length) {
      const p = this.packages.get(stack.pop()!);
      if (!p || !p.dev) continue;
      p.dev = false;
      stack.push(...(adj.get(p.key) ?? []));
    }
    return { kind, name, source, packages: this.packages, edges: this.edges, direct: [...this.direct].map(([key, dev]) => ({ key, dev })), mcp: [] };
  }
}

// ───────────── package-lock.json v2/v3 ─────────────
function packageLock(lock: any, filename: string): Parsed {
  const b = new Builder("npm");
  const entries: Record<string, any> = lock.packages;
  const byPath = new Map<string, Pkg>();
  for (const [path, e] of Object.entries(entries)) {
    if (!path.includes("node_modules/") || e.link) continue;
    const name = e.name ?? path.slice(path.lastIndexOf("node_modules/") + 13);
    const p = b.add(name, e.version, { lockInstallScript: !!e.hasInstallScript });
    if (p) byPath.set(path, p);
  }
  // Node's lookup: ./node_modules, then each parent node_modules up to the workspace root, then the repo root.
  const resolve = (from: string, dep: string): Pkg | undefined => {
    let base = from;
    while (true) {
      const hit = byPath.get(base ? `${base}/node_modules/${dep}` : `node_modules/${dep}`);
      if (hit || !base) return hit;
      const i = base.lastIndexOf("/node_modules/");
      base = i >= 0 ? base.slice(0, i) : "";
    }
  };
  for (const [path, e] of Object.entries(entries)) {
    const deps = Object.keys({ ...e.dependencies, ...e.optionalDependencies, ...e.peerDependencies });
    if (path === "" || !path.includes("node_modules/")) {
      // The root and every workspace folder ("packages/app") are roots of the tree.
      for (const d of Object.keys({ ...e.dependencies, ...e.optionalDependencies })) b.root(resolve(path, d), false);
      for (const d of Object.keys(e.devDependencies ?? {})) b.root(resolve(path, d), true);
      continue;
    }
    const from = byPath.get(path);
    for (const d of deps) b.edge(from, resolve(path, d));
  }
  return b.build("app", entries[""]?.name ?? lock.name ?? filename, `package-lock v${lock.lockfileVersion}`);
}

// ───────────── pnpm-lock.yaml v9 ─────────────
const stripPeers = (v: string) => String(v).replace(/\(.*$/, "");

/** pnpm writes an aliased dependency as "real-name@1.2.3" or "npm:real-name@1.2.3". */
export function pnpmResolve(dep: string, raw: string): { name: string; version: string } {
  const v = stripPeers(raw).replace(/^npm:/, "");
  if (!v.includes("://") && v.indexOf("@", 1) > 0) {
    const s = splitSpec(v);
    if (s.version) return { name: s.name, version: s.version };
  }
  return { name: dep, version: v };
}

/** pnpm 11+ writes two YAML documents: the package manager's own lockfile first, then the project's. Use the largest. */
function pnpmDocument(content: string): any {
  const docs = parseAllDocuments(content, { maxAliasCount: 1000 } as any);
  const list = (Array.isArray(docs) ? docs : [docs]).map((d: any) => d.toJS({ maxAliasCount: 1000 })).filter((d: any) => d && typeof d === "object");
  // The project document declares dependencies; the package manager one only pins pnpm itself.
  const project = (d: any) => Object.values<any>(d.importers ?? {}).some((i) => i?.dependencies || i?.devDependencies || i?.optionalDependencies);
  const size = (d: any) => Object.keys(d.snapshots ?? d.packages ?? {}).length;
  return list.sort((a, b) => Number(project(b)) - Number(project(a)) || size(b) - size(a))[0];
}

function pnpmLock(content: string, filename: string): Parsed {
  const lock: any = pnpmDocument(content);
  if (parseFloat(String(lock?.lockfileVersion ?? 0)) < 9) throw new Error(`pnpm-lock.yaml v${lock?.lockfileVersion} isn't supported yet (pnpm 9+ writes v9).`);
  const b = new Builder("npm");
  for (const id of Object.keys(lock.packages ?? {})) {
    const s = splitSpec(id);
    if (s.version) b.add(s.name, stripPeers(s.version));
  }
  for (const [id, snap] of Object.entries<any>(lock.snapshots ?? {})) {
    const s = splitSpec(stripPeers(id));
    const from = s.version ? b.add(s.name, s.version) : null;
    for (const [dep, ver] of Object.entries<string>({ ...snap?.dependencies, ...snap?.optionalDependencies })) {
      const r = pnpmResolve(dep, ver);
      b.edge(from, b.add(r.name, r.version));
    }
  }
  for (const importer of Object.values<any>(lock.importers ?? {})) {
    for (const [section, dev] of [["dependencies", false], ["optionalDependencies", false], ["devDependencies", true]] as const) {
      for (const [dep, spec] of Object.entries<any>(importer?.[section] ?? {})) {
        const r = pnpmResolve(dep, String(spec?.version ?? spec));
        b.root(b.add(r.name, r.version), dev);
      }
    }
  }
  return b.build("app", filename.replace(/\.ya?ml$/, ""), `pnpm-lock v${lock.lockfileVersion}`);
}

// ───────────── yarn.lock v1 ─────────────
function yarnV1(content: string, filename: string): Parsed {
  const b = new Builder("npm");
  const bySpec = new Map<string, Pkg>();
  const blocks: { pkg: Pkg | null; deps: [string, string][] }[] = [];
  let cur: { specs: string[]; name: string; version: string; deps: [string, string][] } | null = null;
  let inDeps = false;
  const flush = () => {
    if (!cur) return;
    const p = b.add(cur.name, cur.version);
    if (p) cur.specs.forEach((s) => bySpec.set(s, p));
    blocks.push({ pkg: p, deps: cur.deps });
    cur = null;
  };
  const unq = (s: string) => s.trim().replace(/^"|"$/g, "");
  for (const line of content.split(/\r?\n/)) {
    if (!line.trim() || line.startsWith("#")) continue;
    if (!line.startsWith(" ")) {
      flush();
      const specs = line.replace(/:\s*$/, "").split(",").map(unq);
      const alias = specs[0].match(/@npm:(.+)$/)?.[1]; // "alias@npm:real@^1"
      cur = { specs, name: splitSpec(alias ?? specs[0]).name, version: "", deps: [] };
      inDeps = false;
      continue;
    }
    if (!cur) continue;
    const t = line.trim();
    if (/^(dependencies|optionalDependencies):$/.test(t)) inDeps = true;
    else if (line.startsWith("    ") && inDeps) {
      const m = t.match(/^"?([^"\s]+)"?\s+"?([^"]+)"?$/);
      if (m) cur.deps.push([m[1], m[2]]);
    } else {
      inDeps = false;
      const v = t.match(/^version\s+"?([^"\s]+)"?/);
      if (v) cur.version = v[1];
    }
  }
  flush();
  for (const blk of blocks) for (const [d, range] of blk.deps) b.edge(blk.pkg, bySpec.get(`${d}@${range}`));
  b.inferRoots();
  return b.build("app", filename.replace(/\.lock$/, ""), "yarn.lock v1");
}

// ───────────── yarn.lock (Berry, v2+) ─────────────
function yarnBerry(content: string, filename: string): Parsed {
  const lock: Record<string, any> = parseYaml(content, { maxAliasCount: 1000 });
  const b = new Builder("npm");
  const bySpec = new Map<string, Pkg>();
  const pending: { pkg: Pkg | null; deps: Record<string, string> }[] = [];
  const roots: [string, string][] = [];
  let name = filename.replace(/\.lock$/, "");
  for (const [key, val] of Object.entries(lock)) {
    if (key === "__metadata" || !val) continue;
    const res: string = val.resolution ?? key.split(",")[0].trim();
    const pkgName = res.slice(0, res.indexOf("@", 1));
    if (res.includes("@workspace:")) {
      if (res.endsWith("@workspace:.")) name = pkgName;
      for (const [d, r] of Object.entries<string>(val.dependencies ?? {})) if (!String(r).startsWith("workspace:")) roots.push([d, r]);
      continue;
    }
    const p = b.add(pkgName, String(val.version));
    key.split(",").forEach((s) => p && bySpec.set(s.trim(), p));
    pending.push({ pkg: p, deps: { ...val.dependencies, ...val.optionalDependencies } });
  }
  const find = (d: string, r: string) => bySpec.get(`${d}@${r}`) ?? bySpec.get(`${d}@npm:${String(r).replace(/^npm:/, "")}`);
  for (const x of pending) for (const [d, r] of Object.entries(x.deps)) b.edge(x.pkg, find(d, r));
  for (const [d, r] of roots) b.root(find(d, r), false);
  if (!roots.length) b.inferRoots();
  return b.build("app", name, "yarn.lock (Berry)");
}

// ───────────── bun.lock (text, Bun 1.2+) ─────────────
function bunLock(content: string, filename: string): Parsed {
  const json = JSON.parse(content.replace(/,(\s*[}\]])/g, "$1"));
  const b = new Builder("npm");
  const byPath = new Map<string, { pkg: Pkg | null; deps: Record<string, string> }>();
  for (const [path, info] of Object.entries<any>(json.packages ?? {})) {
    if (!Array.isArray(info) || typeof info[0] !== "string") continue;
    const s = splitSpec(info[0]);
    const meta = info.find((x: any) => x && typeof x === "object" && !Array.isArray(x)) ?? {};
    byPath.set(path, { pkg: s.version ? b.add(s.name, s.version) : null, deps: { ...meta.dependencies, ...meta.optionalDependencies } });
  }
  // Nested overrides are "parent/child" (scoped names take two path parts); innermost wins.
  const parts = (p: string) => {
    const t = p.split("/");
    const out: string[] = [];
    for (let i = 0; i < t.length; i++) out.push(t[i].startsWith("@") ? `${t[i]}/${t[++i]}` : t[i]);
    return out;
  };
  const resolve = (from: string, dep: string) => {
    let s = from ? parts(from) : [];
    while (true) {
      const hit = byPath.get([...s, dep].join("/"));
      if (hit || !s.length) return hit?.pkg;
      s = s.slice(0, -1);
    }
  };
  for (const [path, x] of byPath) for (const d of Object.keys(x.deps)) b.edge(x.pkg, resolve(path, d));
  for (const ws of Object.values<any>(json.workspaces ?? {})) {
    for (const d of Object.keys({ ...ws.dependencies, ...ws.optionalDependencies })) b.root(resolve("", d), false);
    for (const d of Object.keys(ws.devDependencies ?? {})) b.root(resolve("", d), true);
  }
  return b.build("app", json.workspaces?.[""]?.name ?? filename.replace(/\.lock$/, ""), `bun.lock v${json.lockfileVersion ?? "?"}`);
}

// ───────────── uv.lock ─────────────
const fromPypi = (src: any) =>
  src.registry ? /^https:\/\/(pypi\.org|files\.pythonhosted\.org)\//.test(String(src.registry)) : !(src.git || src.url || src.path);

function uvLock(content: string, filename: string): Parsed {
  const lock: any = parseToml(content);
  const b = new Builder("PyPI");
  const byName = new Map<string, Pkg[]>();
  const pkgs: { p: Pkg; deps: any[] }[] = [];
  const roots: { d: any; dev: boolean }[] = [];
  let name = filename.replace(/\.lock$/, "");
  const list = (x: any) => (Array.isArray(x) ? x : []);
  for (const pkg of lock.package ?? []) {
    const src = pkg.source ?? {};
    const deps = [...list(pkg.dependencies), ...Object.values<any>(pkg["optional-dependencies"] ?? {}).flatMap(list)];
    if (src.editable !== undefined || src.virtual !== undefined || src.directory !== undefined) {
      if (src.editable === "." || src.virtual === ".") name = String(pkg.name);
      roots.push(...deps.map((d) => ({ d, dev: false })), ...Object.values<any>(pkg["dev-dependencies"] ?? {}).flatMap(list).map((d) => ({ d, dev: true })));
      continue;
    }
    if (!fromPypi(src)) continue;
    const p = b.add(String(pkg.name), String(pkg.version ?? ""));
    if (!p) continue;
    byName.set(p.name, [...(byName.get(p.name) ?? []), p]);
    pkgs.push({ p, deps });
  }
  const pick = (d: any) => {
    const opts = byName.get(normPy(String(d.name))) ?? [];
    return d.version ? opts.find((o) => o.version === String(d.version)) : opts[0];
  };
  for (const x of pkgs) for (const d of x.deps) b.edge(x.p, pick(d));
  for (const r of roots) b.root(pick(r.d), r.dev);
  if (!roots.length) b.inferRoots();
  return b.build("app", name, `uv.lock v${lock.version ?? "?"}`);
}

// ───────────── poetry.lock ─────────────
function poetryLock(content: string, filename: string): Parsed {
  const lock: any = parseToml(content);
  const b = new Builder("PyPI");
  const byName = new Map<string, Pkg>();
  const pkgs: { p: Pkg; deps: string[] }[] = [];
  for (const pkg of lock.package ?? []) {
    // Packages from git, a URL, a folder or a private index (legacy source) aren't on PyPI.
    if (pkg.source?.type && pkg.source.type !== "pypi") continue;
    const p = b.add(String(pkg.name), String(pkg.version));
    if (!p) continue;
    byName.set(p.name, p);
    pkgs.push({ p, deps: Object.keys(pkg.dependencies ?? {}) });
  }
  for (const x of pkgs) for (const d of x.deps) b.edge(x.p, byName.get(normPy(d)));
  b.inferRoots();
  return b.build("app", filename.replace(/\.lock$/, ""), "poetry.lock");
}

// ───────────── requirements.txt (pinned lines) ─────────────
function requirements(content: string, filename: string): Parsed {
  const b = new Builder("PyPI");
  let unpinned = 0;
  for (const raw of content.replace(/\\\r?\n/g, " ").split(/\r?\n/)) {
    const line = raw.replace(/(^|\s)#.*$/, "").trim();
    if (!line || line.startsWith("-")) continue;
    const m = line.match(/^([A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]*\])?\s*===?\s*([0-9][A-Za-z0-9.+!_-]*)/);
    if (m) b.root(b.add(m[1], m[3]), false);
    else unpinned++;
  }
  return b.build("app", filename.replace(/\.txt$/, ""), `requirements.txt${unpinned ? ` (${unpinned} unpinned line${unpinned === 1 ? "" : "s"} skipped)` : ""}`);
}

// ───────────── MCP configs ─────────────
/** Which package an MCP server command runs: npx / bunx / pnpm dlx / yarn dlx (npm), uvx / pipx run / uv tool run (PyPI). */
export function mcpPackage(command: string, args: string[]): { ecosystem: Ecosystem | null; spec: string | null } {
  const bin = command.split(/[\\/]/).pop() ?? command;
  let rest = [...args];
  let eco: Ecosystem | null = null;
  if (["npx", "bunx", "pnpx"].includes(bin)) eco = "npm";
  else if (["pnpm", "yarn"].includes(bin) && rest[0] === "dlx") (eco = "npm"), rest.shift();
  else if (bin === "uvx") eco = "PyPI";
  else if (bin === "pipx" && rest[0] === "run") (eco = "PyPI"), rest.shift();
  else if (bin === "uv" && rest[0] === "tool" && rest[1] === "run") (eco = "PyPI"), (rest = rest.slice(2));
  if (!eco) return { ecosystem: null, spec: null };
  for (let i = 0; i < rest.length; i++) {
    const a = rest[i];
    if (["--package", "-p", "--from"].includes(a)) return { ecosystem: eco, spec: rest[i + 1] ?? null };
    if (/^--(package|from)=/.test(a)) return { ecosystem: eco, spec: a.split("=").slice(1).join("=") };
    if (!a.startsWith("-")) return { ecosystem: eco, spec: a };
  }
  return { ecosystem: eco, spec: null };
}

function mcpConfig(json: any, filename: string): Parsed {
  const f = filename.toLowerCase();
  const client = f.includes("claude_desktop") ? "Claude Desktop" : f.includes("cursor") ? "Cursor" : f.includes("vscode") || json.servers ? "VS Code" : f.includes("windsurf") ? "Windsurf" : "Claude Code";
  const servers: Record<string, any> = { ...(json.mcpServers ?? {}), ...(json.servers ?? {}) };
  for (const proj of Object.values<any>(json.projects ?? {})) Object.assign(servers, proj?.mcpServers ?? {});
  const mcp: McpRef[] = [];
  for (const [name, def] of Object.entries<any>(servers)) {
    if (!def || typeof def !== "object") continue;
    if (def.url || def.type === "http" || def.type === "sse") {
      mcp.push({ key: name, name, client, command: def.url ?? "remote", ecosystem: null, packageName: null, version: null, pinned: true });
      continue;
    }
    const args: string[] = Array.isArray(def.args) ? def.args.map(String) : [];
    const { ecosystem, spec } = mcpPackage(String(def.command ?? ""), args);
    let packageName: string | null = null;
    let version: string | null = null;
    if (spec && ecosystem === "PyPI") {
      const m = spec.match(/^([A-Za-z0-9._-]+)(?:\[[^\]]*\])?(?:==([0-9][^\s]*))?$/);
      packageName = m ? normPy(m[1]) : spec;
      version = m?.[2] ?? null;
    } else if (spec) {
      const s = splitSpec(spec);
      packageName = s.name;
      version = isRegistryVersion(s.version) ? s.version : null;
    }
    mcp.push({ key: name, name, client, command: [def.command, ...args].join(" "), ecosystem, packageName, version, pinned: ecosystem === null || version !== null });
  }
  return { kind: "agent-config", name: `${client} MCP setup`, source: `MCP config (${client})`, packages: new Map(), edges: [], direct: [], mcp };
}
